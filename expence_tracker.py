import csv
import os
from datetime import datetime

# Personal Expense Tracker
FILE_NAME = "expenses.csv"

# Create CSV file if it does not exist
def initialize_file():
    if not os.path.exists(FILE_NAME):
        with open(FILE_NAME, "w", newline="") as file:
            writer = csv.writer(file)
            writer.writerow(["Title", "Amount", "Category", "Date"])


# Read all expenses from CSV
def load_expenses():
    expenses = []

    try:
        with open(FILE_NAME, "r", newline="") as file:
            reader = csv.DictReader(file)

            for row in reader:
                expenses.append(row)

    except FileNotFoundError:
        initialize_file()

    return expenses


# Add a new expense
def add_expense():
    print("\n--- ADD NEW EXPENSE ---")

    title = input("Enter expense title: ").strip()

    if not title:
        print("Title cannot be empty.")
        return

    try:
        amount = float(input("Enter amount: "))

        if amount <= 0:
            print("Amount must be greater than zero.")
            return

    except ValueError:
        print("Invalid amount. Please enter a number.")
        return

    category = input("Enter category: ").strip()

    if not category:
        print("Category cannot be empty.")
        return

    date_input = input("Enter date (DD-MM-YYYY): ").strip()

    try:
        valid_date = datetime.strptime(date_input, "%d-%m-%Y")
        date = valid_date.strftime("%d-%m-%Y")
    except ValueError:
        print("Invalid date. Please use DD-MM-YYYY.")
        return

    with open(FILE_NAME, "a", newline="") as file:
        writer = csv.writer(file)
        writer.writerow([title, amount, category, date])

    print("Expense added successfully!")


# View all expenses
def view_expenses():
    expenses = load_expenses()

    print("\n--- ALL EXPENSES ---")

    if not expenses:
        print("No expenses recorded.")
        return

    for i, expense in enumerate(expenses, start=1):
        print(f"\nExpense {i}")
        print("Title:", expense["Title"])
        print("Amount: Rs.", expense["Amount"])
        print("Category:", expense["Category"])
        print("Date:", expense["Date"])


# Search expenses by category
def search_category():
    expenses = load_expenses()

    category = input("Enter category to search: ").strip().lower()

    found = False

    print("\n--- SEARCH RESULTS ---")

    for expense in expenses:
        if expense["Category"].lower() == category:
            print("\nTitle:", expense["Title"])
            print("Amount: Rs.", expense["Amount"])
            print("Date:", expense["Date"])
            found = True

    if not found:
        print("No expenses found in this category.")


# Calculate total expenses
def calculate_total():
    expenses = load_expenses()

    total = sum(float(expense["Amount"]) for expense in expenses)

    print("\n--- TOTAL EXPENSES ---")
    print(f"Total Spending: Rs. {total:.2f}")


# Display monthly expense summary
def monthly_summary():
    expenses = load_expenses()

    month = input("Enter month and year (MM-YYYY): ").strip()

    try:
        datetime.strptime(month, "%m-%Y")
    except ValueError:
        print("Invalid format. Enter month as MM-YYYY.")
        return

    total = 0
    count = 0

    print("\n--- MONTHLY EXPENSE SUMMARY ---")

    for expense in expenses:
        expense_date = datetime.strptime(
            expense["Date"], "%d-%m-%Y"
        )

        if expense_date.strftime("%m-%Y") == month:
            total += float(expense["Amount"])
            count += 1

    print("Month:", month)
    print("Number of expenses:", count)
    print(f"Total monthly spending: Rs. {total:.2f}")


# Delete an expense
def delete_expense():
    expenses = load_expenses()

    if not expenses:
        print("No expenses available to delete.")
        return

    print("\n--- DELETE EXPENSE ---")

    for i, expense in enumerate(expenses, start=1):
        print(
            f"{i}. {expense['Title']} - "
            f"Rs. {expense['Amount']} - "
            f"{expense['Category']} - {expense['Date']}"
        )

    try:
        choice = int(input("Enter expense number to delete: "))

        if choice < 1 or choice > len(expenses):
            print("Invalid expense number.")
            return

    except ValueError:
        print("Please enter a valid number.")
        return

    deleted = expenses.pop(choice - 1)

    with open(FILE_NAME, "w", newline="") as file:
        fieldnames = ["Title", "Amount", "Category", "Date"]
        writer = csv.DictWriter(file, fieldnames=fieldnames)

        writer.writeheader()
        writer.writerows(expenses)

    print(deleted["Title"], "deleted successfully!")


# Main menu
def main():
    initialize_file()

    while True:
        print("\n================================")
        print("     PERSONAL EXPENSE TRACKER")
        print("================================")
        print("1. Add New Expense")
        print("2. View All Expenses")
        print("3. Search by Category")
        print("4. Calculate Total Expenses")
        print("5. Monthly Expense Summary")
        print("6. Delete an Expense")
        print("7. Exit")

        choice = input("\nEnter your choice (1-7): ").strip()

        if choice == "1":
            add_expense()

        elif choice == "2":
            view_expenses()

        elif choice == "3":
            search_category()

        elif choice == "4":
            calculate_total()

        elif choice == "5":
            monthly_summary()

        elif choice == "6":
            delete_expense()

        elif choice == "7":
            print("\nThank you for using Personal Expense Tracker!")
            print("Your expenses are saved in the CSV file.")
            break

        else:
            print("Invalid choice. Please select 1-7.")


# Run the application
if __name__ == "__main__":
    main()
